// Drives C again's search by keys, headless: ⌘J opens it, words find, ↓ and Enter open, Escape shuts.
import { chromium } from '@playwright/test'

const browser = await chromium.launch()
const heading = (page) => page.locator('[data-conversation-bar]').innerText()
const results = []
for (const d of ['c1', 'c2', 'c3', 'c4']) {
  const page = await browser.newPage({ viewport: { width: 1280, height: 760 } })
  await page.goto(`http://localhost:6177/?d=${d}&named=1`)
  await page.waitForTimeout(700)
  await page.locator('body').click({ position: { x: 900, y: 600 } })
  await page.keyboard.press('Meta+j')
  await page.waitForTimeout(250)
  const field = page.getByRole('combobox', { name: 'Search conversations' })
  const opened = await field.isVisible()
  await page.keyboard.type('webhook')
  await page.waitForTimeout(100)
  const found = await page.getByRole('option').allInnerTexts()
  await page.keyboard.press('Enter')
  await page.waitForTimeout(400)
  const afterEnter = (await heading(page)).replace(/\s+/g, ' ')
  await page.keyboard.press('Meta+j')
  await page.waitForTimeout(250)
  await page.keyboard.press('ArrowUp')
  await page.keyboard.press('ArrowUp')
  await page.keyboard.press('ArrowUp')
  await page.keyboard.press('ArrowUp')
  await page.keyboard.press('Enter')
  await page.waitForTimeout(400)
  const afterUp = (await heading(page)).replace(/\s+/g, ' ')
  await page.keyboard.press('Meta+j')
  await page.waitForTimeout(250)
  await page.keyboard.press('Escape')
  await page.waitForTimeout(300)
  const shut = !(await field.isVisible())
  results.push({ d, opened, found: found.map((one) => one.replace(/\s+/g, ' ')), afterEnter, afterUp, shut })
  await page.close()
}
await browser.close()
process.stdout.write(`${JSON.stringify(results, null, 1)}\n`)
