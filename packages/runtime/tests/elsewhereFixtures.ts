export const gitIn = (cwd: string, ...args: Array<string>) =>
  execFileSync('git', args, {
    cwd,
    encoding: 'utf8',
    env: {
      ...process.env,
      GIT_AUTHOR_NAME: 'Test',
      GIT_AUTHOR_EMAIL: 'test@althar.test',
      GIT_COMMITTER_NAME: 'Test',
      GIT_COMMITTER_EMAIL: 'test@althar.test',
    },
  }).trim()

const write = (path: string, body: string | Buffer) => {
  mkdirSync(dirname(path), { recursive: true })
  writeFileSync(path, body)
}
const jsonl = (records: ReadonlyArray<unknown>) => `${records.map((one) => JSON.stringify(one)).join('\n')}\n`

/** A digest of every file under `root`, its path and bytes: what "unchanged to the byte" is checked by. */
export const digest = (root: string) => {
  const hash = createHash('sha256')
  const walk = (at: string) => {
    for (const name of readdirSync(at).toSorted()) {
      const path = join(at, name)
      const stat = statSync(path)
      if (stat.isDirectory()) walk(path)
      else {
        hash.update(path)
        hash.update(readFileSync(path))
      }
    }
  }
  walk(root)
  return hash.digest('hex')
}

